  function detect() {
    try {
      const q = new URLSearchParams(location.search).get("lang");
      if (q === "en" || q === "zh") return q;
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved === "en" || saved === "zh") return saved;
    } catch (_) { /* ignore */ }
    return "zh";
  }

  let lang = detect();

  function t(key) {
    const pack = STR[lang] || STR.zh;
    return pack[key] != null ? pack[key] : (STR.zh[key] != null ? STR.zh[key] : key);
  }

  function apply(root) {
    const scope = root || document;
    scope.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      if (!key) return;
      const val = t(key);
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        if (el.hasAttribute("data-i18n-placeholder")) el.placeholder = val;
        else el.value = val;
      } else if (el.hasAttribute("data-i18n-html")) {
        el.innerHTML = val;
      } else {
        el.textContent = val;
      }
    });
    scope.querySelectorAll("[data-i18n-attr]").forEach((el) => {
      const spec = el.getAttribute("data-i18n-attr");
      if (!spec) return;
      spec.split(";").forEach((pair) => {
        const [attr, key] = pair.split(":").map((s) => s && s.trim());
        if (attr && key) el.setAttribute(attr, t(key));
      });
    });
    document.documentElement.lang = lang === "en" ? "en" : "zh-CN";
    const titleKey = document.body && document.body.getAttribute("data-i18n-title");
    if (titleKey) document.title = t(titleKey);
    const descKey = document.body && document.body.getAttribute("data-i18n-desc");
    if (descKey) {
      const meta = document.querySelector('meta[name="description"]');
      if (meta) meta.setAttribute("content", t(descKey));
    }
  }

  function setLang(next) {
    lang = next === "en" ? "en" : "zh";
    try {
      localStorage.setItem(STORAGE_KEY, lang);
      const url = new URL(location.href);
      url.searchParams.set("lang", lang);
      history.replaceState(null, "", url.pathname + url.search + url.hash);
    } catch (_) { /* ignore */ }
    apply(document);
    document.dispatchEvent(new CustomEvent("fg:lang", { detail: { lang } }));
  }

  function toggle() {
    setLang(lang === "en" ? "zh" : "en");
  }

  global.FGi18n = { t, apply, setLang, toggle, get lang() { return lang; }, STR };
